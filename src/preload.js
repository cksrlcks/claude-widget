const { contextBridge, ipcRenderer } = require("electron")

contextBridge.exposeInMainWorld("api", {
  onState: (cb) => ipcRenderer.on("state", (_e, s) => cb(s)),
  getState: () => ipcRenderer.invoke("get-state"),
  refresh: () => ipcRenderer.invoke("refresh"),
  checkIntegrations: () => ipcRenderer.invoke("check-integrations"),
  openSettings: () => ipcRenderer.invoke("open-settings"),
  switchAccount: (id) => ipcRenderer.invoke("switch-account", id),
  loginNew: () => ipcRenderer.invoke("login-new"),
  mcpLogin: (names) => ipcRenderer.invoke("mcp-login", names),
  openConnectors: () => ipcRenderer.invoke("open-connectors"),
  openStore: () => ipcRenderer.invoke("open-store"),
  onCatalog: (cb) => ipcRenderer.on("catalog", (_e, c) => cb(c)),
  getCatalog: () => ipcRenderer.invoke("store-catalog"),
  reloadCatalog: () => ipcRenderer.invoke("store-reload"),
  installPlugin: (id) => ipcRenderer.invoke("store-install", id),
  pluginAction: (action, id) => ipcRenderer.invoke("store-action", action, id),
  marketplaceAction: (action, value) => ipcRenderer.invoke("store-marketplace", action, value),
  openUrl: (url) => ipcRenderer.invoke("open-url", url),
  removeProfile: (id) => ipcRenderer.invoke("remove-profile", id),
  updateProfile: (id, patch) => ipcRenderer.invoke("update-profile", id, patch),
  setWatch: (keys) => ipcRenderer.invoke("set-watch", keys),
  setInterval: (min) => ipcRenderer.invoke("set-interval", min),
  setAutoStart: (on) => ipcRenderer.invoke("set-auto-start", on),
  setMini: (v) => ipcRenderer.invoke("set-mini", v),
  setHeight: (h) => ipcRenderer.invoke("set-height", h),
  accountMenu: () => ipcRenderer.invoke("account-menu"),
  dragStart: (p) => ipcRenderer.send("drag-start", p),
  dragMove: (p) => ipcRenderer.send("drag-move", p),
  dragEnd: () => ipcRenderer.send("drag-end"),
})
