// motion: index.css의 px-* 애니메이션 이름

export type Motion = "bob" | "squash" | "float" | "tilt" | "hop" | "peck" | "bounce" | "waddle"

export type Sprite = {
  name: string
  bg: string
  palette: Record<string, string>
  rows: string[]
  motion: Motion
  /** 움직이지 않는 줄 (Clawd 다리처럼 바닥에 붙어 있어야 하는 부분) */
  fixedRows?: number[]
}

